const interp = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`)) : s);

export function makeI18n(lang) {
  const L = T[lang] || T.en;
  const t = (key, vars) => interp(L[key] !== undefined ? L[key] : key, vars);
  return {
    lang, t,
    DIAS: DIAS_CORTO[lang] || DIAS_CORTO.en,
    DIAS_LARGO: DIAS_LARGO[lang] || DIAS_LARGO.en,
    MESES: MESES[lang] || MESES.en,
  };
}

